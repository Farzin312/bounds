# ---------------------------------------------------------------------------
# Version + hash stamping (confined to agent-config files; never structural JSON)
# ---------------------------------------------------------------------------
def _version() -> str:
    """Installed bounds version, for stamping generated files.

    Reuses the single resolved value from the package (``bounds.__version__``) so the stamp
    always matches what the rest of the CLI reports, and never raises on this structural-free path.
    """
    try:
        from bounds import __version__
        return __version__
    except Exception:  # pragma: no cover - defensive
        return "unknown"


def _body_hash(body: str) -> str:
    """8-char hex digest of an in-marker body (stamp line excluded by the caller).

    Used only to (a) stamp generated files and (b) detect hand-edits / staleness. It never
    feeds any structural hash — the cache and validation engine compute their own digests over
    source content and are wholly independent of this function.
    """
    return hashlib.sha256(body.encode("utf-8")).hexdigest()[:8]


def _stamp_line(fmt: str, body: str) -> str:
    """The version+hash stamp line for ``body`` in the requested marker format."""
    h = _body_hash(body)
    if fmt == _YAML:
        return f"# BOUNDS:GENERATED v={_version()} h={h}"
    return f"<!-- BOUNDS:GENERATED v={_version()} h={h} -->"


def _build_block(fmt: str, body: str) -> str:
    """Wrap ``body`` (the inner content, no markers) in markers + a leading version/hash stamp."""
    start, end = (_YAML_START, _YAML_END) if fmt == _YAML else (_MD_START, _MD_END)
    inner = body.rstrip("\n")
    return f"{start}\n{_stamp_line(fmt, inner)}\n{inner}\n{end}"


# ---------------------------------------------------------------------------
# Public entry point
# ---------------------------------------------------------------------------
def run_agent(project_root: Path, *, mode: str, only: set[str] | None = None) -> dict:
    """Run the cross-agent protocol and return a JSON-serializable payload.

    Args:
        project_root: Repository root. Config files are written relative to it.
        mode: One of ``"sync"``, ``"detect"``, ``"check"``.
        only: Optional set of agent keys (from :data:`AGENT_KEYS`) to restrict the operation
            to. ``None`` means all eight agents. ``AGENTS.md`` (the canonical contract) is
            always written on ``sync`` regardless of selection, since every pointer references it.

    Returns:
        A dict whose shape depends on ``mode``. All path lists are sorted and POSIX-relative.

    Raises:
        BoundsError: ``E_USAGE`` for an unknown ``mode`` or an unknown agent key in ``only``.
    """
    root = Path(project_root)
    if mode not in VALID_MODES:
        raise errors.BoundsError(
            errors.E_USAGE,
            f"unknown agent mode {mode!r}",
            fix=f"use one of: {', '.join(sorted(VALID_MODES))}",
        )
    selected = _resolve_selection(only)

    if mode == "detect":
        return _detect(root)
    if mode == "check":
        return _check(root, selected)
    return _sync(root, selected)


# ---------------------------------------------------------------------------
# Selection helpers
# ---------------------------------------------------------------------------
def _resolve_selection(only: set[str] | None) -> list[str]:
    """Validate ``only`` and return the agent keys to operate on, in stable order.

    Raises ``BoundsError(E_USAGE)`` for any unknown key so a typo fails loudly rather than
    silently writing nothing.
    """
    if only is None:
        return list(AGENT_KEYS)
    unknown = sorted(only - set(AGENT_KEYS))
    if unknown:
        raise errors.BoundsError(
            errors.E_USAGE,
            f"unknown agent key(s): {', '.join(unknown)}",
            fix=f"valid keys: {', '.join(AGENT_KEYS)}",
        )
    return [k for k in AGENT_KEYS if k in only]


# ---------------------------------------------------------------------------
# Expected-body resolution (one home: both sync and check ask "what should this file hold?")
# ---------------------------------------------------------------------------
def _expected_body(agent: "_Agent", sdd_cfg: dict | None = None) -> str:
    """The inner in-marker body (no markers, no stamp) this agent's file should currently hold.

    Single source for both the writer (``_sync``) and the verifier (``_check``) so the two can
    never disagree about what "up to date" means.
    """
    sdd_cfg = sdd_cfg or _sdd_config(None)
    if agent.canonical or agent.path == CANONICAL_NAME:
        return _append_sdd_body(CANONICAL_BODY.rstrip("\n"), "canonical", sdd_cfg)
    if agent.dedicated:
        return _append_sdd_body(_dedicated_body(agent).rstrip("\n"), agent.key, sdd_cfg)
    return _append_sdd_body(_pointer_block_body(agent.fmt).rstrip("\n"), agent.key, sdd_cfg)


def _sdd_config(root: Path | None) -> dict:
    """Return resolved SDD config for generated agent artifacts, fail-soft when absent/broken."""
    raw = {}
    if root is not None:
        try:
            found = manifest_loader.find_root(root)
            if found is not None:
                rootm = manifest_loader.load_root(found)
                if isinstance(rootm.sdd, dict):
                    raw = rootm.sdd
        except Exception:  # noqa: BLE001 - agent sync must still work with a broken root manifest
            raw = {}
    enabled = bool(raw.get("enabled", False))
    agent = str(raw.get("agent") or "generic")
    if agent not in config.SDD_AGENTS:
        agent = "generic"
    requested = raw.get("phases")
    if requested is None:
        requested = config.SDD_PHASES
    phases = [p for p in config.SDD_PHASES if p in set(requested)]
    return {"enabled": enabled, "agent": agent, "phases": phases}


def _append_sdd_body(body: str, agent_key: str, sdd_cfg: dict) -> str:
    """Append the active SDD contract to generated agent text only when opted in."""
    if not sdd_cfg.get("enabled"):
        return body
    return body.rstrip("\n") + "\n\n" + _sdd_body(agent_key, sdd_cfg).rstrip("\n")


def _sdd_body(agent_key: str, sdd_cfg: dict) -> str:
    """Agent-facing SDD phase map expressed as Bounds commands, not a new workflow engine."""
    phase_uses = {
        "specify": ("`bounds overview` / `bounds list`", "ground the spec in the real subsystem map, coverage, and boundaries"),
        "clarify": ("`bounds describe <name>` / `bounds where <symbol>`", "answer what the current verified contract of X is"),
        "plan": ("`bounds impact <name>`", "include blast radius and declared boundaries in the implementation plan"),
        "tasks": ("`bounds impact <name>`", "scope and order tasks by subsystem dependency edges"),
        "analyze": ("`bounds validate` / `bounds preflight`", "cross-check plan/tasks against architecture before coding"),
        "implement": ("`bounds validate --quick`", "catch drift after each edit; manifest updates are part of intentional spec changes"),
        "verify": ("`bounds preflight --ci`", "final deterministic architecture gate"),
    }
    lines = [
        "## Bounds in Spec-Driven Development",
        "",
        f"SDD is enabled for `{sdd_cfg.get('agent', 'generic')}`; this `{agent_key}` artifact wires Bounds into the project's customized SDD loop.",
        "Bounds stays zero-LLM: it provides verified architecture facts and gates while the agent handles prose spec work.",
        "",
        "### Phase contract",
    ]
    for phase in config.SDD_PHASES:
        if phase not in set(sdd_cfg.get("phases", config.SDD_PHASES)):
            continue
        command, use = phase_uses[phase]
        lines.append(f"- **{phase}** → {command} — {use}.")
    lines.extend(
        [
            "",
            "### Freshness contract",
            "- If the spec intentionally changes public surface, update the manifest in the same spec/plan change.",
            "- Run `bounds calibrate --dump-baseline` only after the manifest reflects the intended contract.",
            "- `bounds validate --quick` in the edit loop catches accidental drift; `bounds preflight --ci` is the final gate.",
            "- For unsupported-language subsystems, keep hand-authored exposes in the manifest; calibrate routes unverifiable entries to review instead of deleting them.",
        ]
    )
    return "\n".join(lines)


def _front_matter(agent: "_Agent") -> str:
    """Tool-activating front-matter that must sit at the very top of a dedicated file.

    Lives *outside* the managed markers so the tool parses it at line 1 and so a human can
    tweak it without tripping hand-edit detection:
      * Claude — ``description`` surfaces the file as a usable ``/bounds`` slash command.
      * Cursor — ``alwaysApply: true`` makes a ``.mdc`` an always-on rule (no front-matter =
        a dormant "Manual" rule).
      * Windsurf — ``trigger: always_on`` applies the rule universally.
    Agents without dedicated front-matter return ``""``.
    """
    desc = "Read this project's architecture via the Bounds CLI, not raw .bounds files"
    front = {
        "claude": f"---\ndescription: {desc}\n---\n",
        "cursor": f"---\ndescription: {desc}\nalwaysApply: true\n---\n",
        "windsurf": f"---\ntrigger: always_on\ndescription: {desc}\n---\n",
    }
    return front.get(agent.key, "")


def _dedicated_body(agent: "_Agent") -> str:
    """Inner body for a dedicated (bounds-only) file's managed block.

    Claude's file is a real slash command, so it forwards ``$ARGUMENTS`` to the CLI: running
    ``/bounds describe auth`` actually executes ``bounds describe auth`` (and a bare ``/bounds``
    falls back to ``bounds overview -H``). The CLI keeps space-separated subcommands — we never
    rename a command or hyphenate it. Cursor/Windsurf get the short shared pointer body (they
    are passive always-on rules, not invokable commands).
    """
    if agent.key == "claude":
        return _CLAUDE_COMMAND_BODY
    return "# Bounds\n\n" + _AGENT_POINTER_BODY


