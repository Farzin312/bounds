# mode = check
# ---------------------------------------------------------------------------
def _check(root: Path, selected: list[str]) -> dict:
    """Report, for each detected-and-selected agent, whether its bounds config is up to date.

    We intersect with detection so a check reports only on agents actually in use — selecting
    all eight on a Claude-only repo won't flag cursor/gemini/etc. We classify each target as:

      * ``missing``    — the config file doesn't exist, or exists but carries no bounds block
                         (no markers / never synced).
      * ``stale``      — a bounds block is present but its content no longer matches what the
                         installed CLI would generate (the contract moved on, the body was
                         hand-edited, or — for a dedicated file — its front-matter was removed).
                         Refresh with ``bounds agent --sync``.
      * ``configured`` — a bounds block is present and its stamped hash matches the current
                         expected body exactly.

    Returns ``{"ok": bool, "missing": [...], "stale": [...], "configured": [...], "fix": "..."}``
    with sorted key lists; ``ok`` is True iff nothing is missing *and* nothing is stale. The
    ``fix`` field is only present when there is something to fix.
    """
    detected = set(_detect(root)["detected"])
    targets = [k for k in selected if k in detected]
    sdd_cfg = _sdd_config(root)

    configured: list[str] = []
    missing: list[str] = []
    stale: list[str] = []
    for key in targets:
        status = _config_status(root, _AGENTS[key], sdd_cfg)
        if status == "missing":
            missing.append(key)
        elif status == "stale":
            stale.append(key)
        else:
            configured.append(key)

    result: dict = {
        "ok": not missing and not stale,
        "missing": sorted(missing),
        "stale": sorted(stale),
        "configured": sorted(configured),
    }
    if missing or stale:
        result["fix"] = "bounds agent --sync"
    return result


def _config_status(root: Path, agent: "_Agent", sdd_cfg: dict | None = None) -> str:
    """Classify ``agent`` as ``missing`` / ``stale`` / ``configured`` across ALL its files.

    The primary signal is the pointer/canonical file (``missing`` ⇒ never synced; ``stale`` ⇒
    synced-but-outdated). On top of that, any native command/skill artifact that is *present but
    corrupted/outdated* (a hand-edit, an old stamp) downgrades the agent to ``stale`` — that is the
    real risk the gate must catch, since the tool would load a broken file. A merely *absent*
    artifact does not: it is an un-generated enhancement that an idempotent re-sync adds
    non-destructively, and several agents (codex/opencode) are fully wired by ``AGENTS.md`` alone,
    so requiring their optional artifact would falsely flag them after a single-agent sync.
    """
    sdd_cfg = sdd_cfg or _sdd_config(root)
    pointer = _target_status(root, agent.path, agent.fmt, _expected_body(agent, sdd_cfg),
                             agent.dedicated, _front_matter(agent))
    if pointer != "configured":
        return pointer  # missing (never synced) or stale (outdated) — primary signal wins
    for art in _AGENT_ARTIFACTS.get(agent.key, ()):
        if (root / Path(art.path)).exists():
            body = _append_sdd_body(art.body.rstrip("\n"), agent.key, sdd_cfg)
            if _target_status(root, art.path, art.fmt, body, True, art.front) != "configured":
                return "stale"  # a present artifact is broken/outdated — re-sync to refresh
    # An always-loaded memory file (CLAUDE.md) that exists but lacks/holds an outdated bounds block
    # downgrades to stale so the gate tells you to re-sync. A merely-absent one does not (an
    # idempotent --sync creates it non-destructively), mirroring the optional-artifact rule above.
    mem = _MEMORY_FILES.get(agent.key)
    if mem is not None and (root / Path(mem)).exists():
        mem_body = _append_sdd_body(_AGENT_POINTER_BODY.rstrip("\n"), agent.key, sdd_cfg)
        if _target_status(root, mem, _MARKDOWN, mem_body, False, "") != "configured":
            return "stale"
    return "configured"


def _target_status(root: Path, rel: str, fmt: str, expected_body: str,
                   dedicated: bool, front: str) -> str:
    """Classify one managed file as ``missing`` / ``stale`` / ``configured``.

    "Up to date" means the file has our markers AND the in-marker block carries a stamp whose
    hash matches what the installed CLI would generate now. A present-but-un-stamped block, an
    older-hash stamp, a hand-edited body, or (for a dedicated file that expects it) removed
    front-matter all read as ``stale``. The version string is deliberately not part of staleness —
    it moves every commit, so the body hash is the contract signal.
    """
    target = root / Path(rel)
    if not target.exists():
        return "missing"
    start = _YAML_START if fmt == _YAML else _MD_START
    end = _YAML_END if fmt == _YAML else _MD_END
    text = _read_text(target)
    if start not in text or end not in text:
        return "missing"  # file exists but was never synced (no bounds block)
    inner = _extract_inner(text, start, end)
    if inner is None:
        return "missing"
    _version_stamp, recorded, body = _split_stamp(inner, fmt)
    if recorded is None or recorded != _body_hash(expected_body):
        return "stale"
    if _body_hash(body) != recorded:
        return "stale"
    if dedicated and front and not _has_front_matter(text):
        return "stale"
    return "configured"


# ---------------------------------------------------------------------------
# Filesystem helpers (centralized so encoding/newlines stay consistent)
