"""Cross-agent protocol: teach coding agents to read architecture via the CLI.

The problem this solves: AI coding agents (Claude Code, Cursor, Copilot, Gemini, …) each
have their own out-of-band convention for project instructions, and when left to their own
devices they may read the raw `.bounds/` files — the binary cache and the unverified YAML
manifests — which both defeats tree-sitter verification *and* burns context on data the CLI
already compresses.

This module writes a single canonical contract in ``AGENTS.md`` — the cross-ecosystem
standard file that agents already read — plus a small per-agent *pointer* file in each
agent's native config location, all conveying the same essentials: use ``bounds list`` /
``bounds describe`` / ``bounds validate --quick`` to read architecture, never read raw
``.bounds`` artifacts, and treat the CLI as the API. ``AGENTS.md`` is the source of truth; every per-tool pointer references it, so
there is exactly one place the contract lives.

Design constraints (enforced repo-wide):
  * Pure stdlib, no new dependencies.
  * These are *generated artifacts*, not structural JSON. Each managed block is wrapped in
    ``<!-- BOUNDS:START -->`` / ``<!-- BOUNDS:END -->`` markers and stamped with the bounds
    version + an 8-char content hash. That stamp is the ONLY non-deterministic element and it
    is confined to these agent-config files — it never reaches any ``describe`` / ``validate``
    / ``list`` JSON, nor any cache/validation hash. Everything *around* a managed block (and
    the body apart from the stamp) is deterministic, so a re-sync of unedited files is a no-op.
  * Fail soft: the only fatal condition is genuine misuse (bad ``mode`` / bad agent key),
    which raises ``BoundsError(E_USAGE)``. A *shared* config a human wrote — one with no markers
    but mentioning bounds, or with markers whose body a human edited — is never clobbered; it is
    reported (``skipped_custom``) and left untouched. A *dedicated* (bounds-only) file is ours to
    keep current: a legacy unmarked one is migrated to a stamped block and deleted front-matter
    is restored.

The three modes:
  * ``sync``   — write ``AGENTS.md`` and the selected agents' pointer files; return what changed.
  * ``detect`` — heuristically report which agents' tool footprints are present.
  * ``check``  — for detected agents, report which have a stale/missing bounds config.
"""

