# Bounds-owned artifact paths that were RENAMED after we already shipped them, so repos synced
# by an older bounds carry a stale orphan at the old path. These are regenerable (the *correct*
# paths are written in the `_AGENT_ARTIFACTS` loop of this same sync), so a re-sync self-cleans
# the orphan — the same self-clean pattern as the legacy state.json in `cache.store.save_state`.
# Each here is provably NOT a current artifact path: opencode's singular `command/` was renamed to
# the plural `commands/`, and codex's `.codex/skills/` was renamed to the shared `.agents/skills/`
# spec location — so removing these can never delete a file this sync just wrote.
_LEGACY_ARTIFACTS: tuple[tuple[str, str], ...] = (
    # (legacy path, owning agent) — cleaned only when that agent is in THIS sync, so the
    # replacement (written above in the _AGENT_ARTIFACTS loop) is guaranteed present.
    (".opencode/command/bounds.md", "opencode"),   # -> .opencode/commands/bounds.md (plural)
    (".codex/skills/bounds/SKILL.md", "codex"),     # -> .agents/skills/bounds/SKILL.md (open spec)
)


# ---------------------------------------------------------------------------
# mode = sync
# ---------------------------------------------------------------------------
def _sync(root: Path, selected: list[str]) -> dict:
    """Write the canonical ``AGENTS.md`` and the selected agents' pointer files.

    ``AGENTS.md`` is always (re)written first — it is the source of truth every pointer
    references — then each selected agent that has its *own* file gets a marked, stamped block.
    Codex/OpenCode are satisfied by ``AGENTS.md`` itself, so selecting them is a no-op beyond
    the canonical write.

    Every file is marker-managed: content *outside* the markers (including a dedicated file's
    front-matter and any human additions) is preserved byte-for-byte, and only the block inside
    the markers is refreshed. If a file's in-marker body was hand-edited since we last stamped
    it (its content no longer matches the recorded hash), it is reported ``skipped_custom`` and
    left untouched rather than clobbered.

    Returns sorted, POSIX-relative ``created`` / ``updated`` / ``unchanged`` / ``skipped_custom``
    path lists, a ``skip_reasons`` map (``path -> "authored" | "hand-edited"``) explaining each
    skip, and ``canonical`` (always ``"AGENTS.md"``). ``unchanged`` lets a no-op sync confirm
    "everything already current" instead of looking like nothing happened.
    """
    buckets = _Buckets()
    sdd_cfg = _sdd_config(root)

    # 1. Canonical AGENTS.md — always written, as a marked block so any other AGENTS.md
    #    content the project keeps is preserved.
    canonical_path = root / CANONICAL_NAME
    rel_canonical = CANONICAL_NAME
    outcome = _upsert_block(
        canonical_path,
        _MARKDOWN,
        _expected_body(_AGENTS["codex"], sdd_cfg),
    )
    buckets.record(outcome, rel_canonical)

    # 2. Per-tool files for the selected agents (AGENTS.md already handled above).
    done: set[str] = {CANONICAL_NAME}
    for key in selected:
        agent = _AGENTS[key]
        if agent.canonical or agent.path in done:
            continue  # covered by the canonical AGENTS.md write
        done.add(agent.path)
        outcome = _upsert_block(
            root / Path(agent.path),
            agent.fmt,
            _expected_body(agent, sdd_cfg),
            prefix=_front_matter(agent),
            dedicated=agent.dedicated,
        )
        buckets.record(outcome, Path(agent.path).as_posix())

    # 2b. Always-loaded memory files (e.g. Claude's CLAUDE.md). A marked pointer block so the agent
    #     is told about Bounds from the file it ALWAYS reads, not only an on-demand command/skill.
    #     Non-destructive: created if absent, else the block is added/refreshed while the human's own
    #     content is preserved byte-for-byte. The body is the shared per-agent pointer body.
    for key in selected:
        mem = _MEMORY_FILES.get(key)
        if mem is None or mem in done:
            continue
        done.add(mem)
        outcome = _upsert_block(
            root / Path(mem),
            _MARKDOWN,
            _append_sdd_body(_AGENT_POINTER_BODY.rstrip("\n"), key, sdd_cfg),
        )
        buckets.record(outcome, Path(mem).as_posix())

    # 3. Targeted, invokable command/skill files (native to each agent). Each is bounds-owned
    #    (dedicated), so it is marker-managed + idempotent like the rest. Agents with no
    #    committable command mechanism (aider) have none — never faked.
    for key in selected:
        for art in _AGENT_ARTIFACTS.get(key, ()):
            if art.path in done:
                continue
            done.add(art.path)
            outcome = _upsert_block(
                root / Path(art.path), art.fmt,
                _append_sdd_body(art.body.rstrip("\n"), key, sdd_cfg),
                prefix=art.front, dedicated=True,
            )
            buckets.record(outcome, Path(art.path).as_posix())

    # 4. Self-clean renamed orphans — but ONLY for agents in THIS sync. The step-3 loop above
    #    already wrote the current path for each selected agent, so removing that agent's stale
    #    file at its prior (renamed) path is safe: the replacement is guaranteed present. Gating on
    #    `owner in selected` means a selective sync (e.g. --only gemini) never strips another
    #    agent's file without writing its replacement. Only these exact bounds-owned paths are ever
    #    touched, and none collides with a current artifact (see `_LEGACY_ARTIFACTS`). Fail-soft:
    #    cleanup never raises. An emptied parent dir is removed too, but only if empty — we never
    #    recursively delete a dir that still holds other files.
    selected_set = set(selected)
    for rel, owner in _LEGACY_ARTIFACTS:
        if owner not in selected_set:
            continue
        legacy = root / Path(rel)
        if legacy.is_file():
            try:
                legacy.unlink()
            except OSError:
                pass
            try:
                parent = legacy.parent
                if not any(parent.iterdir()):
                    parent.rmdir()
            except OSError:
                pass

    return {
        "created": sorted(buckets.created),
        "updated": sorted(buckets.updated),
        "unchanged": sorted(buckets.unchanged),
        "skipped_custom": sorted(buckets.skipped),
        "skip_reasons": {k: buckets.reasons[k] for k in sorted(buckets.reasons)},
        "canonical": rel_canonical,
    }


class _Buckets:
    """Accumulates per-file ``_upsert_block`` outcomes into the sync report's sorted lists.

    A skip carries *why* (``"authored"`` = a file the human wrote that already mentions bounds;
    ``"hand-edited"`` = our managed block whose body a human changed) so the human renderer can
    explain it honestly and point at the fix, rather than the old flat "hand-edited" wording that
    mislabeled files which were never bounds-managed in the first place.
    """

    __slots__ = ("created", "updated", "unchanged", "skipped", "reasons")

    def __init__(self) -> None:
        self.created: set[str] = set()
        self.updated: set[str] = set()
        self.unchanged: set[str] = set()
        self.skipped: set[str] = set()
        self.reasons: dict[str, str] = {}

    def record(self, outcome: str, rel: str) -> None:
        if outcome == "created":
            self.created.add(rel)
        elif outcome == "updated":
            self.updated.add(rel)
        elif outcome == "unchanged":
            self.unchanged.add(rel)
        elif outcome == "skipped_authored":
            self.skipped.add(rel)
            self.reasons[rel] = "authored"
        elif outcome == "skipped_hand_edited":
            self.skipped.add(rel)
            self.reasons[rel] = "hand-edited"


def _upsert_block(
    target: Path, fmt: str, body: str, prefix: str = "", dedicated: bool = False
) -> str:
    """Insert or refresh our marked+stamped block in ``target``, preserving other content.

    ``body`` is the inner content (no markers); this wraps it via :func:`_build_block`.
    ``prefix`` is the tool-activating front-matter a dedicated file must lead with. ``dedicated``
    marks a file bounds owns wholly (Claude/Cursor/Windsurf): such a file is always brought up to
    date — a legacy bounds file with no markers is *migrated* to a stamped block rather than
    skipped, and front-matter a human deleted is restored so the tool can't silently de-activate.

    Returns:
        ``created``        — file did not exist; created with ``prefix`` + our block.
        ``updated``        — our marked block was inserted/refreshed, or a dedicated file was
                             migrated / had its front-matter restored.
        ``unchanged``      — file already held our block with an identical body and (for a
                             dedicated file) intact front-matter. A differing version stamp
                             alone does not count as a change.
        ``skipped_hand_edited`` — a *shared* file whose in-marker body a human edited since we
                             stamped it. Left untouched (never clobber a human's edit).
        ``skipped_authored`` — a *shared* file with no markers that already mentions bounds, so a
                             human wrote it. Left untouched. Dedicated files are never skipped —
                             we own them.
    """
    start, end = (_YAML_START, _YAML_END) if fmt == _YAML else (_MD_START, _MD_END)
    block = _build_block(fmt, body)

    if not target.exists():
        _write_text(target, (prefix + "\n" if prefix else "") + block + "\n")
        return "created"

    existing = _read_text(target)

    if start in existing and end in existing:
        current_inner = _extract_inner(existing, start, end)
        if current_inner is not None and _is_hand_edited(current_inner, fmt):
            return "skipped_hand_edited"  # human edited inside the markers — never clobber.

        # Refresh the block, and for a dedicated file restore front-matter a human may have
        # removed (which would otherwise silently de-activate the tool).
        new = _replace_block(existing, start, end, block)
        if dedicated:
            new = _ensure_front_matter(new, prefix)

        # A differing version stamp alone is not a real change: the dev version moves every
        # commit, so decide on the body — and, for a dedicated file that *expects* front-matter
        # (non-empty prefix), its presence. A dedicated file with no front-matter (e.g. a TOML
        # command, a Cursor command) must still read as unchanged when its body matches.
        current_body = _split_stamp(current_inner, fmt)[2] if current_inner is not None else None
        front_ok = not dedicated or not prefix or _has_front_matter(existing)
        if current_body == body and front_ok:
            return "unchanged"
        _write_text(target, new)
        return "updated"

    # No markers.
    if dedicated:
        # We own a dedicated file wholly: migrate legacy bounds content (written before stamping
        # existed) into a stamped block, keeping any front-matter a human may have tweaked.
        front = _leading_front_matter(existing) or prefix
        _write_text(target, (front + "\n" if front else "") + block + "\n")
        return "updated"

    # Shared file: if it already talks about bounds, a human wrote it — don't clobber.
    if _looks_bounds_authored(existing):
        return "skipped_authored"

    # Unrelated content with no markers: append our block, preserving theirs.
    sep = "" if existing.endswith("\n\n") else ("\n" if existing.endswith("\n") else "\n\n")
    _write_text(target, existing + sep + block + "\n")
    return "updated"


def _has_front_matter(text: str) -> bool:
    """True when ``text`` opens (at line 1) with a ``---``-fenced front-matter block.

    The fence must lead the file for the tool to parse it, so a leading blank line counts as
    missing — and a re-sync will restore it.
    """
    return text.startswith("---")


def _leading_front_matter(text: str) -> str:
    """Return the leading ``---``-fenced front-matter block (trailing newline included), or ``""``."""
    if not text.startswith("---"):
        return ""
    lines = text.split("\n")
    for idx in range(1, len(lines)):
        if lines[idx].strip() == "---":
            return "\n".join(lines[: idx + 1]) + "\n"
    return ""


def _ensure_front_matter(text: str, prefix: str) -> str:
    """Restore a dedicated file's leading front-matter when a human removed it.

    Without it the tool silently de-activates (Claude drops the ``/bounds`` command, Cursor and
    Windsurf stop auto-applying their rule). An existing front-matter is left untouched so a
    human's edits to the description survive.
    """
    if not prefix or _has_front_matter(text):
        return text
    return prefix + "\n" + text


def _extract_inner(text: str, start: str, end: str) -> str | None:
    """Return the content between the first ``start`` and ``end`` markers (exclusive), or None.

    The returned text is the *raw* in-marker block, stamp line included; callers strip the
    stamp themselves when they need the body alone.
    """
    i = text.find(start)
    if i == -1:
        return None
    j = text.find(end, i + len(start))
    if j == -1:
        return None
    return text[i + len(start):j].strip("\n")


def _split_stamp(inner: str, fmt: str) -> tuple[str | None, str | None, str]:
    """Split a raw in-marker block into ``(version, hash, body)``.

    The stamp is the first line when present; ``version``/``hash`` are None for a legacy
    (un-stamped) block, with the whole text returned as the body.
    """
    pattern = _YAML_STAMP_RE if fmt == _YAML else _MD_STAMP_RE
    lines = inner.split("\n")
    if lines:
        m = pattern.fullmatch(lines[0].strip())
        if m:
            return m.group("v"), m.group("h"), "\n".join(lines[1:]).strip("\n")
    return None, None, inner


def _is_hand_edited(inner: str, fmt: str) -> bool:
    """True when an existing in-marker block was edited by a human since we stamped it.

    A block we wrote carries a stamp whose hash matches its body. If the recorded hash and the
    body's actual hash disagree, a human touched the content — refuse to clobber it. A legacy
    block with no stamp at all is treated as ours (we wrote it before stamping existed), so it
    is safe to refresh.
    """
    _v, recorded, body = _split_stamp(inner, fmt)
    if recorded is None:
        return False  # legacy un-stamped block we authored — safe to refresh.
    return _body_hash(body) != recorded


def _replace_block(text: str, start: str, end: str, block: str) -> str:
    """Replace the first ``start``…``end`` marked region (inclusive) with ``block``.

    Operates on the raw text so surrounding content — before the start marker and after the
    end marker — is preserved byte-for-byte.
    """
    i = text.index(start)
    j = text.index(end, i) + len(end)
    return text[:i] + block + text[j:]


_BOUNDS_COMMAND_RE = re.compile(
    r"\bbounds\s+"
    r"(list|describe|validate|preflight|overview|init|impact|discover|calibrate|agent|ci|cache)\b"
)
_BOUNDS_HEADING_RE = re.compile(r"(?m)^\s*#.*\bbounds\b")


def _looks_bounds_authored(text: str) -> bool:
    """Heuristic: does an unmarked shared file already contain hand-written bounds content?

    Used only to decide ``skipped_custom``. We look for unambiguous signals that a human wrote
    bounds guidance, so we err toward *not* clobbering:
      * a real CLI invocation — the word ``bounds`` immediately followed by a known subcommand;
      * the inline-code form ```` `bounds` ````;
      * a markdown heading line that names Bounds.

    Critically, plain English prose such as "out of bounds" or "bounds checking" must NOT
    match — those are safe to append our block to. Returns False for any such unrelated content.
    """
    lowered = text.lower()
    return (
        bool(_BOUNDS_COMMAND_RE.search(lowered))
        or "`bounds`" in lowered
        or bool(_BOUNDS_HEADING_RE.search(lowered))
    )


